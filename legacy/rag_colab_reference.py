class StandardTask(Task):
  def __init__(self, n_shots:int, skill_use: bool, selection_mode:Selection = Selection.RANDOM):
    super().__init__(n_shots,skill_use,selection_mode)

  def get_dataset(self):
    dataset = []
    for datapoint in self.testdataset:
      new_datapoint = datapoint.copy()
      prompt = self.build_input(datapoint, PROMPT_BUILDER)

      new_datapoint["instruction"] = prompt["instruction"]
      new_datapoint["question"] = prompt["question"]
      new_datapoint["output_prefix"] = prompt["output_prefix"]
      new_datapoint["validation_examples"] = prompt["validation_examples"]
      new_datapoint["input"] = prompt

      dataset.append(new_datapoint)

    return dataset

