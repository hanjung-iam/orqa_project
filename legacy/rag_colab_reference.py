def parse_prediction(answer):
  answer = answer.strip().upper()

  if answer in VALID:
    return ltr_to_idx(answer)

  candidates = re.findall(r"\b([ABCD])\b", answer)
  if candidates:
    return ltr_to_idx(candidates[-1])

  return -1

