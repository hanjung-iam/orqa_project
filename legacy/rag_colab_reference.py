def reciprocal_rank_fusion(dense_results,bm25_results,rrf_k=RRF_K,final_top_k=FINAL_TOP_K):
  fused_scores = {}
  chunk_lookup = {}
  for result in dense_results:
    chunk_id = (result["metadata"].get("chunk_id"))
    rank = result["rank"]
    rrf_score = (1 / (rrf_k + rank))
    fused_scores[chunk_id] = (
        fused_scores.get(chunk_id,0) + rrf_score
    )

    chunk_lookup[chunk_id] = result
  for result in bm25_results:
    chunk_id = (result["chunk_id"])
    rank = result["rank"]
    rrf_score = (1 / (rrf_k + rank))
    fused_scores[chunk_id] = (
        fused_scores.get(chunk_id,0) + rrf_score
    )
    if chunk_id not in chunk_lookup:
      chunk_lookup[chunk_id] = result
  ranked_chunk_ids = sorted(
      fused_scores,
      key=fused_scores.get,
      reverse=True
  )
  top_chunk_ids = (ranked_chunk_ids[:final_top_k])

  fused_results = []
  for final_rank, chunk_id in enumerate(top_chunk_ids,start=1):
    chunk_result = (chunk_lookup[chunk_id])
    fused_result = {
        "rank": final_rank,
        "chunk_id": chunk_id,
        "content": (chunk_result["content"]),
        "metadata": (chunk_result["metadata"]),
        "rrf_score": (fused_scores[chunk_id])
    }
    fused_results.append(fused_result)

  return fused_results

