def prepare_metadata(chunk):
  metadata={}
  for key, value in chunk.items():
    if key == "content":
      continue
    if isinstance(value, list):
      metadata[key] = json.dumps(value)
      # ChromaDB Metadata 不適合直接儲存 Python List 因此轉換成 JSON String

    elif value is None: metadata[key] = ""

    else:
      metadata[key] = value
  return metadata

