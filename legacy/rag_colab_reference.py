CHUNK_SIZE = 2048  # 設定每個 Chunk 的最大字元數
STRIDE = 256
# 當內容超出 CHUNKING_SIZE 時，重新切片，相鄰 Chunk 之間保留的重疊字元數

# 當內容超出 CHUNKING_SIZE 時，進行重新切片
def split_content(content, chunk_size=CHUNK_SIZE, stride=STRIDE):
  content = content.strip()
  if len(content) <= chunk_size:
    return [content]

  paragraphs = re.split(r"\n\s*\n", content) # 依照空白行切割

  chunks = []
  temp_chunk = ""
  for paragraph in paragraphs:
    paragraph = paragraph.strip()
    if not paragraph:
      continue

    if len(temp_chunk) + len(paragraph) + 2 <= chunk_size:
      if temp_chunk:
        temp_chunk += "\n\n"
      temp_chunk += paragraph
    else:
      if temp_chunk:
        chunks.append(temp_chunk.strip())

      if len(paragraph) <= chunk_size:
        temp_chunk = paragraph
      else:
        start = 0
        while start < len(paragraph):
          end = start + chunk_size
          chunk = paragraph[start:end]
          chunks.append(chunk)
          if end >= len(paragraph):
            break
          start = end - stride
        temp_chunk = ""

  if temp_chunk:
    chunks.append(temp_chunk.strip())

  return chunks

def heading_parsing(content):
  heading_pattern = re.compile(r"^(#{1,6})\s+(.+?)\s*$", re.MULTILINE) #辨識標題
  headings = list(heading_pattern.finditer(content))

  sections = []
  heading_stack = []

  first_heading = headings[0].start() # 找出第一個標題
  pre_content = content[:first_heading].strip() # 第一個標題前的內容
  if pre_content:
    sections.append({"heading_path": "Document Intro",
            "content": pre_content})

  for index, heading in enumerate(headings):
    level = len(heading.group(1)) # 計算level | # -> level 1 | ## ->level 2
    text = heading.group(2).strip() # 文字內容

    while(heading_stack and heading_stack[-1]["level"] >= level):
      heading_stack.pop()
    heading_stack.append({"level": level, "text": text})


    if index+1 < len(headings): # 還有下一個標題
      content_end = headings[index+1].start()

    else:
      content_end = len(content)

    section_content = content[heading.end():content_end].strip()
    heading_path = " > ".join(item["text"] for item in heading_stack)


    if section_content:
      sections.append({
          "heading_path": heading_path,
          "content": section_content
      })

  return sections

def build_heading_chunk(document, chunk_size=CHUNK_SIZE, stride=STRIDE):
  sections = heading_parsing(document["content"])
  chunks = []
  local_chunk_index = 0
  for index, section in enumerate(sections):
    section_chunks = split_content(section["content"], chunk_size, stride)
    for idx, chunk_content in enumerate(section_chunks):
      chunks.append({
          "document_name": document["document_name"],
          "chunk_strategy": "heading_based",
          "section_index":index,
          "chunk_index": idx,
          "chunk_heading": section["heading_path"],
          "content": chunk_content
      })
      local_chunk_index += 1
      #print(f"version_0.md num of chunks = {local_chunk_index}")
  return chunks

def case_parsing(content):
  case_pattern = re.compile(r"^##\s+CASE\s+(.+?)\s*$", re.MULTILINE)
  cases_matches = list(case_pattern.finditer(content))

  cases = []

  for index, case in enumerate(cases_matches):
    case_id = case.group(1).strip()
    case_start = case.start() # 目前開始的位置

    if index+1 < len(cases_matches): # 還有下一個case
      content_end = cases_matches[index+1].start() # 下一個開始的位置

    else:
      content_end = len(content)

    section_content = content[case_start:content_end].strip()


    cases.append({
        "case_id": case_id,
        "content": section_content
    })

  return cases

def case_sec_parsing(case_content):
  section_pattern = re.compile(r"^(###)\s+(.+?)\s*$",re.MULTILINE)
  section_matches = list(section_pattern.finditer(case_content))
  # 找出目前 CASE 中所有 Level-3 Section
  sections = []
  case_heading_match = re.match(r"^##\s+CASE\s+.+?\s*$", case_content, re.MULTILINE)
  # 找出 CASE 本身的 Heading

  if section_matches:
    metadata_start = (
        case_heading_match.end()
        if case_heading_match
        else 0
    )
    # Metadata 從 CASE Heading 結束後開始

    metadata_end = section_matches[0].start()
    # Metadata 到第一個 ### Section 前結束

    metadata = case_content[metadata_start:metadata_end].strip()

    if metadata:
      sections.append({
           "section_name": "Case Metadata",
           "content": metadata

      })

  else:
    return [{
        "section_name": "Full Case",
        "content": case_content
    }]

  for index, section_match in enumerate(section_matches):

    section_name = section_match.group(2).strip()
    content_start = section_match.end()

    if index + 1 < len(section_matches):
      content_end = section_matches[index + 1].start()

    else:
      content_end = len(case_content)

    section_content = case_content[content_start:content_end].strip()
    # 擷取目前 Section 的內容
    if section_content:
      sections.append({
          "section_name": section_name,
          "content": section_content
      })
  return sections




def build_case_chunk(document, chunk_size=CHUNK_SIZE, stride=STRIDE):
  cases = case_parsing(document["content"])
  chunks = []

  for case_index, case in enumerate(cases):
    case_id = case["case_id"]
    case_content = case["content"]

    if len(case_content) <= chunk_size:
      chunks.append({
          "document_name": document["document_name"],
          "strategy": "case_based",
          "case_id": case_id,
          "section_names": ["Full Case"],
          "content": case_content
      })
      continue

    case_sections = case_sec_parsing(case_content)
    current_content = f"## CASE {case_id}\n"
    current_sec_names = []
    chunk_index_in_case = 0
    for section in case_sections:
      section_name = section["section_name"]
      section_text = (f"### {section_name}\n"
                f"{section['content']}")

      if len(current_content) + len(section_text) + 2 <= chunk_size:
        current_content += ("\n\n"+ section_text) # 將 Section 加入目前 Chunk
        current_sec_names.append(section_name) # 記錄目前 Chunk 包含這個 Section

      else:
        if current_sec_names:
          chunks.append({
              "document_name": document["document_name"],
              "chunk_strategy": "case_aware",
              "case_id": case_id,
              "chunk_index_in_case": chunk_index_in_case,
              "section_names": current_sec_names.copy(),
              "content": current_content.strip()
          })
          chunk_index_in_case += 1
        if len(section_text) <= chunk_size: # 如果目前單一 Section 本身沒有超過 Chunk Size
          current_content = (
              f"## CASE {case_id}\n\n"
              f"{section_text}"
          )
          current_sec_names = [section_name]
        else: # 如果單一 Section 本身也超過 Chunk Size
          long_section_chunks = split_content(section_text,chunk_size=(chunk_size - len(f"## CASE {case_id}\n\n")),stride=STRIDE)
          for long_part_index, long_part in enumerate(long_section_chunks):
            chunks.append({
                "document_name": document["document_name"],
                "chunk_strategy": "case_aware",
                "case_id": case_id,
                "chunk_index_in_case":chunk_index_in_case,
                "section_names": [section_name],
                "content":
                  f"## CASE {case_id}\n\n"
                  f"{long_part}"
            })
            chunk_index_in_case += 1

          current_content = (f"## CASE {case_id}\n")
          current_sec_names = []


    if current_sec_names:
      chunks.append({
          "document_name": document["document_name"],
          "chunk_strategy": "case_aware",
          "case_id": case_id,
          "chunk_index_in_case":chunk_index_in_case,
          "section_names":current_sec_names.copy(),
          "content": current_content.strip()
       })

  return chunks

def build_hybrid_chunks(documents, chunk_size=CHUNK_SIZE, stride=STRIDE):
  all_chunks = []
  for document in documents:
    document_name = document["document_name"]
    if document_name == "version_0.md":
      document_chunks = build_heading_chunk(document=document,chunk_size=chunk_size,stride=stride)

    elif document_name == "StructuredOR.md":
      document_chunks = build_case_chunk(document=document,chunk_size=chunk_size,stride=stride)
    else:
      document_chunks = build_heading_chunk(document=document,chunk_size=chunk_size,stride=stride)

    all_chunks.extend(document_chunks)

    for index, chunk in enumerate(all_chunks):
      chunk["chunk_id"] = (f"chunk_{index:06d}")

  return all_chunks

